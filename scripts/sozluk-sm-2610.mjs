const FILES = [
  ["src/i18n/dicts.tr.json", TR],
  ["src/i18n/dicts.en.json", EN],
  ["src/i18n/dicts.ar.json", AR],
  ["src/i18n/dicts.id.json", ID],
  ["src/i18n/dicts.ur.json", UR],
];

for (const [file, keys] of FILES) {
  const j = JSON.parse(fs.readFileSync(file, "utf8"));
  let ekle = 0, varmus = 0;
  for (const [k, v] of Object.entries(keys)) {
    if (j[k] === undefined) { j[k] = v; ekle++; } else varmus++;
  }
  fs.writeFileSync(file, JSON.stringify(j, null, 2) + "\n");
  console.log(`${file}: +${ekle} eklendi, ${varmus} zaten vardı → toplam ${Object.keys(j).length}`);
}
